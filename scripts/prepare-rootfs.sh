# ------------------------------------------- USB-gadget: автозапуск и ключи
# Флаги читает /etc/init.d/local (см. выше): usbnet-enabled -> `usbnet on`,
# ssh-enabled -> dropbear. Снять автозапуск на плате: `usbnet auto off`.
