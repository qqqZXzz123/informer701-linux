# --- /etc/securetty: УДАЛИТЬ -------------------------------------------------
# Alpine поставляет /etc/securetty со списком console, tty0..tty11, ttyS0.. и т.д.
# busybox login для root сверяет с ним короткое имя терминала, которое получает
# через ttyname(STDIN_FILENO). В musl ttyname() читает /proc/self/fd/0, поэтому
# без смонтированного /proc (а его монтировал openrc, которого в minirootfs нет)
# имя получается NULL -> "UNKNOWN", и root отсекается ДО запроса пароля:
#
#     (none) login: root
#     Login incorrect
#     login[44]: invalid password for 'root' on 'UNKNOWN'
#
# Файла нет -> busybox считает любой терминал разрешённым. Плата без сети,
# консоль одна (UART0), поэтому ограничение ничего не даёт.
# /proc теперь всё равно монтируется в /etc/init.d/rcS до запуска getty.
if [ -f "$DEST/etc/securetty" ]; then
    mv "$DEST/etc/securetty" "$DEST/etc/securetty.alpine-orig"
    rm -f "$DEST/etc/securetty"
    echo "   + /etc/securetty удалён (копия: /etc/securetty.alpine-orig)"
fi

