# Ключи хоста dropbear создаём сразу, чтобы первая загрузка не тратила на это
# время и чтобы ключ не менялся от старта к старту (иначе ssh-клиент на ПК
# будет ругаться на сменившийся host key). Если qemu-arm-static недоступен -
# ключи сгенерирует сама плата при первом `usbnet ssh on`.
if [ -n "${QEMU_ARM:-}" ] && [ -x "${QEMU_ARM}" ] && [ -x "$DEST/usr/bin/dropbearkey" ]; then
    mkdir -p "$DEST/dev"
    for t in ed25519 ecdsa; do
        if "$QEMU_ARM" -L "$DEST" "$DEST/usr/bin/dropbearkey" -t "$t" \
               -f "$DEST/etc/dropbear/dropbear_${t}_host_key" >/dev/null 2>&1; then
            echo "   + dropbear host key: $t"
        else
            echo "   ! ключ $t не создался - сгенерируется на плате" >&2
        fi
    done
    if "$QEMU_ARM" -L "$DEST" "$DEST/usr/bin/dropbearkey" -t rsa -s 2048 \
           -f "$DEST/etc/dropbear/dropbear_rsa_host_key" >/dev/null 2>&1; then
        echo "   + dropbear host key: rsa"
    else
        echo "   ! ключ rsa не создался (не критично, есть ed25519)" >&2
    fi
    chmod 600 "$DEST/etc/dropbear/"* 2>/dev/null || true
fi

