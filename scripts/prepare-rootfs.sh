#!/bin/bash
# Prepare the root filesystem (Alpine minirootfs armv7) for the Informer 701.
#
#   usage: ./prepare-rootfs.sh <alpine-minirootfs.tar.gz> <target-dir> [root-password]
#
# Unlike a stock Alpine minirootfs this one is busybox-init based:
#   * /etc/inittab has no openrc calls (openrc is not in minirootfs, and the
#     stock inittab therefore spams "can't run '/sbin/openrc'" three times and
#     respawns getty on six non-existent ttys);
#   * /proc, /sys, /dev/pts, /run, /tmp and /boot are mounted at sysinit;
#   * the hostname is set (otherwise the prompt says "(none) login:");
#   * the serial console is on ttyS0 at 115200 8N1;
#   * diagnostic helpers are installed in /usr/local/bin.
#
# Optional: QEMU_ARM=/usr/bin/qemu-arm-static makes the root password hash be
# generated by the target's own busybox (guaranteed to match what busybox login
# verifies at runtime). Falls back to python3 crypt(3) otherwise.
set -euo pipefail

TARBALL="$1"
DEST="$2"
ROOT_PASS="${3:-informer701}"
BUILD="${BUILD:-dev}"
# Заводской пункт меню (default в extlinux.conf). С b016 это lowopp: полная
# таблица OPP, но все точки @ 1.4 В - проверено на плате в b015 (переходы
# 1008 -> 864 -> 624 МГц прошли, vdd-cpu всё время 1400 мВ, dmesg чистый).
# Значение пишется в /etc/boot-default, его читают bootnext и /etc/init.d/local.
BOOT_DEFAULT="${BOOT_DEFAULT:-lowopp}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
PKGS="${PKGS:-$HERE/pkgs}"

rm -rf "$DEST"; mkdir -p "$DEST"
tar -xzf "$TARBALL" -C "$DEST"

# ------------------------------------------------------------- extra packages
# i2c-tools (i2cdetect/i2cget/i2cdump + libi2c), memtester, devmem2,
# dropbear (SSH-сервер + scp), busybox-extras (udhcpd - DHCP-сервер для
# USB-гаджета, telnetd - запасная консоль, httpd/tftpd)
INSTALLED=""
extract_apk() {  # $1 = имя пакета (без версии), $2 = файл .apk
    tar -xzf "$2" -C "$DEST" \
        --exclude='.PKGINFO' --exclude='.SIGN*' --exclude='.trigger' \
        --exclude='.pre-install' --exclude='.post-install' \
        --exclude='.pre-upgrade' --exclude='.post-upgrade' \
        --exclude='.pre-deinstall' --exclude='.post-deinstall' \
        --exclude='.needsrestart' 2>/dev/null || true
    INSTALLED="$INSTALLED $1"
    # манифест для `pkg baked`: apk не знает об этих пакетах (распакованы tar'ом),
    # а пользователю полезно видеть, что именно лежит в образе.
    mkdir -p "$DEST/etc/apk"
    ver=$({ tar -xzOf "$2" .PKGINFO 2>/dev/null || true; } | awk -F' = ' '/^pkgver/{print $2; exit}')
    echo "$1 ${ver:-?}" >> "$DEST/etc/apk/baked.txt"
    echo "   + $1${ver:+ $ver}"
}
apk_name() { basename "$1" .apk | sed -E 's/-[0-9][^-]*(-r[0-9]+)?$//'; }

# критичные пакеты (порядок важен: busybox-extras в конце, его ссылки делаем ниже)
for apk in i2c-tools memtester devmem2 dropbear dropbear-scp dropbear-dbclient busybox-extras; do
    if [ -f "$PKGS/$apk.apk" ]; then
        extract_apk "$apk" "$PKGS/$apk.apk"
    else
        echo "   ! $PKGS/$apk.apk not found - skipping" >&2
    fi
done

# b021+: ставим ВСЕ остальные .apk из pkgs/ (WiFi: wpa_supplicant/iw/hostapd/
# dnsmasq/wireless-regdb, kmod, iproute2, iptables, usbutils, dosfstools,
# e2fsprogs, nano/htop/picocom, tzdata, haveged, ...). Базовые пакеты
# minirootfs пропускаем - они уже на месте, а busybox-binsh/yash-binsh вообще
# заменили бы /bin/sh (busybox ash проверен годами работы этого образа).
SKIP_APKS="musl musl-utils apk-tools alpine-baselayout alpine-baselayout-data
           alpine-keys busybox busybox-binsh ca-certificates-bundle libcrypto3
           libssl3 scanelf ssl_client zlib libc-utils yash yash-binsh"
for f in "$PKGS"/*.apk; do
    [ -e "$f" ] || continue
    nm=$(apk_name "$f")
    case " $SKIP_APKS " in *" $nm "*) echo "   = $nm (базовый пакет minirootfs - пропущен)"; continue ;; esac
    case " $INSTALLED " in *" $nm "*) continue ;; esac
    extract_apk "$nm" "$f"
done
# --- kmod: modprobe/depmod ДОЛЖНЫ быть настоящими. Модули ядра сжаты xz
# --- (CONFIG_MODULE_COMPRESS_XZ), а busybox modprobe xz не понимает: без kmod
# --- не загрузится ни один WiFi-драйвер. kmod кладёт бинарники в /bin, а
# --- ссылки busybox живут в /sbin (в PATH раньше) - перенаправляем их.
if [ -x "$DEST/bin/kmod" ]; then
    for t in modprobe depmod insmod rmmod lsmod modinfo; do
        ln -sf /bin/kmod "$DEST/sbin/$t"
        ln -sf /bin/kmod "$DEST/bin/$t" 2>/dev/null || true
    done
    echo "   + kmod: /{bin,sbin}/{modprobe,depmod,insmod,rmmod,lsmod,modinfo} -> /bin/kmod"
fi

# --- iptables: в ядре НЕТ CONFIG_NF_TABLES, а apk кладёт /sbin/iptables ->
# --- xtables-nft-multi, который отвечает "Failed to initialize nft: Protocol
# --- not supported". Значит все привычные имена должны вести на legacy-вариант
# --- (xtables-legacy-multi). /etc/profile ставит /usr/local/bin первым, но
# --- скрипты, вызванные напрямую как /sbin/iptables, сломались бы.
for t in iptables ip6tables iptables-save iptables-restore; do
    if [ -e "$DEST/sbin/$t-legacy" ]; then
        ln -sf "/sbin/$t-legacy" "$DEST/usr/local/bin/$t"
        ln -sf "$t-legacy" "$DEST/sbin/$t"
    fi
done
# --- nft-варианты iptables в этом образе неработоспособны: CONFIG_NF_TABLES в
# --- ядре нет, xtables-nft-multi отвечает "Failed to initialize nft", а
# --- iptables-translate/ip6tables-translate вообще падают в segfault (поймано
# --- прогоном в QEMU). Удаляем их вместе с multi, чтобы не путали: остаются
# --- только legacy-имена. (libmnl/libnftnl нужны iproute2 - их не трогаем.)
if [ -e "$DEST/sbin/xtables-nft-multi" ]; then
    REMOVED=0
    for l in "$DEST"/sbin/*; do
        [ -L "$l" ] || continue
        case "$(readlink "$l")" in
            xtables-nft-multi|/sbin/xtables-nft-multi) rm -f "$l"; REMOVED=$((REMOVED+1)) ;;
        esac
    done
    rm -f "$DEST/sbin/xtables-nft-multi"
    echo "   + iptables: убрано $REMOVED nft-симлинков и xtables-nft-multi (в ядре нет NF_TABLES)"
fi

# save/restore в iptables-legacy называются наоборот: iptables-legacy-save
for t in iptables ip6tables; do
    if [ -e "$DEST/sbin/$t-legacy-save" ]; then
        ln -sf "$t-legacy-save"    "$DEST/sbin/$t-save"
        ln -sf "$t-legacy-restore" "$DEST/sbin/$t-restore"
        ln -sf "/sbin/$t-legacy-save"    "$DEST/usr/local/bin/$t-save"
        ln -sf "/sbin/$t-legacy-restore" "$DEST/usr/local/bin/$t-restore"
    fi
done

# --- остальное в единый PATH (/usr/local/bin стоит первым)
mkdir -p "$DEST/usr/local/bin"
# ВАЖНО: цели симлинков - АБСОЛЮТНЫЕ пути корневой ФС платы (/usr/sbin/...),
# а не путь сборочного хоста и не "../sbin/..." (из /usr/local/bin это ведёт в
# /usr/local/sbin, которого нет). Битые ссылки = молча неработающие wifi ap /
# usbnet nat / accel / ssh - ловили это прогоном в QEMU.
for t in i2cdetect i2cget i2cset i2cdump i2ctransfer; do
    [ -e "$DEST/usr/sbin/$t" ] && ln -sf "/usr/sbin/$t" "$DEST/usr/local/bin/$t"
done
for t in iw wpa_supplicant wpa_cli wpa_passphrase hostapd hostapd_cli dnsmasq \
         lsusb usb-devices ip ss tc nano htop picocom xz unxz lzcat iwconfig \
         iwlist iwgetid haveged blkid resize2fs tune2fs lsblk \
         fsck.vfat mkfs.vfat fsck.fat mkfs.fat e2fsck fsck.ext4 mke2fs; do
    [ -e "$DEST/usr/local/bin/$t" ] && continue
    for d in usr/sbin usr/bin sbin bin; do
        if [ -e "$DEST/$d/$t" ]; then ln -sf "/$d/$t" "$DEST/usr/local/bin/$t"; break; fi
    done
done

# --- busybox-extras: сам apk кладёт только /bin/busybox-extras, ссылки на
# --- applet'ы обычно создаёт post-install скрипт busybox - делаем их сами
if [ -x "$DEST/bin/busybox-extras" ]; then
    for t in udhcpd dumpleases telnetd httpd tftpd ftpd inetd tcpsvd; do
        ln -sf /bin/busybox-extras "$DEST/usr/local/bin/$t"
    done
    echo "   + busybox-extras applets: udhcpd dumpleases telnetd httpd tftpd ftpd"
fi
# dropbear лежит в /usr/sbin - дублируем ссылку в привычный PATH
[ -e "$DEST/usr/sbin/dropbear" ] && ln -sf /usr/sbin/dropbear "$DEST/usr/local/bin/dropbear"
# dbclient - SSH-клиент (можно подключаться с платы наружу и тянуть файлы)
[ -e "$DEST/usr/bin/dbclient" ] && ln -sf /usr/bin/dbclient "$DEST/usr/local/bin/ssh"
mkdir -p "$DEST/etc/dropbear" && chmod 700 "$DEST/etc/dropbear"
mkdir -p "$DEST/root/.ssh" && chmod 700 "$DEST/root/.ssh"
# udhcpd пишет сюда файл аренд
mkdir -p "$DEST/var/lib/udhcpd"

# ------------------------------------------------- прошивки WiFi (linux-firmware)
# Выборка файлов из linux-firmware под драйверы, включённые в этом ядре:
# rtlwifi (Realtek), mediatek (mt7601u/mt76x0u/mt76x2u), rt2800usb/rt73usb,
# ath9k_htc, ath6k, carl9170, rsi, mrvl (mwifiex_usb), brcm, regulatory.db.
# Полный список того, чего не хватает конкретному адаптеру: на плате `wifi fw`.
if [ -d "$HERE/firmware" ]; then
    mkdir -p "$DEST/lib/firmware"
    cp -a "$HERE/firmware/." "$DEST/lib/firmware/"
    echo "   + firmware: $(find "$DEST/lib/firmware" -type f | wc -l) файлов, $(du -sh "$DEST/lib/firmware" | cut -f1)"
else
    echo "   ! $HERE/firmware нет - образ будет без прошивок WiFi" >&2
fi

# ------------------------------------------------------- модули ядра (b021+)
# MODULES=<каталог с lib/modules/...> - результат `make modules_install`.
# Без модулей не заработает ни WiFi (cfg80211/mac80211 и драйверы), ни exFAT/NTFS.
if [ -n "${MODULES:-}" ] && [ -d "$MODULES/lib/modules" ]; then
    mkdir -p "$DEST/lib"
    cp -a "$MODULES/lib/modules/." "$DEST/lib/modules/"
    nk=$(find "$DEST/lib/modules" -name '*.ko*' | wc -l)
    kver=$(basename "$(ls -d "$DEST"/lib/modules/*)")
    echo "   + modules: $nk шт., $(du -sh "$DEST/lib/modules" | cut -f1) ($kver)"
    if ! ls "$DEST/lib/modules/$kver/modules.dep" >/dev/null 2>&1; then
        echo "   ! нет modules.dep - на сборочном хосте не отработал depmod?" >&2
        echo "   ! поставьте kmod (apt-get install kmod) и повторите modules_install" >&2
    fi
    # сборочное дерево ядра на плате не нужно (ссылка build/ будет битой)
    rm -f "$DEST/lib/modules/$kver/build" "$DEST/lib/modules/$kver/source"
elif [ -n "${MODULES:-}" ]; then
    echo "   ! MODULES=$MODULES не содержит lib/modules" >&2
else
    echo "   = MODULES не задан - образ без модулей (WiFi работать не будет)" >&2
fi

# ------------------------------------------------------------------- inittab
cat > "$DEST/etc/inittab" <<'EOF'
# Informer 701 (N708H6, Allwinner A10) - busybox init, headless
::sysinit:/etc/init.d/rcS

# debug UART: PB22/PB23 = test points TP20 (TX) / TP21 (RX), 115200 8N1

# Вход без пароля включён по умолчанию (лабораторная плата, консоль только
# последовательная). Логин/пароль при этом тоже работают: root / informer701.
# Вернуть запрос логина:  autologin-off && reboot
ttyS0::respawn:/sbin/getty -n -L -l /sbin/autologin 115200 ttyS0

# обычный вариант с запросом логина:
#ttyS0::respawn:/sbin/getty -L 115200 ttyS0 vt100

::ctrlaltdel:/sbin/reboot
::shutdown:/bin/umount -a -r
EOF

mkdir -p "$DEST/etc/init.d"
cat > "$DEST/etc/init.d/rcS" <<'EOF'
#!/bin/sh
# Informer 701 sysinit - runs from busybox init, no openrc involved

# PATH нужен полный: /etc/profile добавляет /usr/local/bin только для
# login-оболочек, а udhcpd/dumpleases/usbnet-помощники живут именно там и
# вызываются отсюда (при автозапуске), а не из-под логина.
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export PATH

/bin/hostname -F /etc/hostname 2>/dev/null

# /dev: обычно его монтирует само ядро (CONFIG_DEVTMPFS_MOUNT=y) до запуска
# init, но при загрузке из initramfs этого не происходит - без /dev нет ни
# /dev/console, ни /dev/urandom (dropbear без него зависает), ни /dev/ttyS0.
mountpoint -q /dev 2>/dev/null || /bin/mount -t devtmpfs devtmpfs /dev 2>/dev/null
mkdir -p /dev/pts /dev/shm /run/lock
mountpoint -q /proc    || /bin/mount -t proc     proc     /proc
mountpoint -q /sys     || /bin/mount -t sysfs    sysfs    /sys
mountpoint -q /dev/pts || /bin/mount -t devpts   devpts   /dev/pts
mountpoint -q /run     || /bin/mount -t tmpfs    tmpfs    /run
mountpoint -q /tmp     || /bin/mount -t tmpfs    tmpfs    /tmp
mountpoint -q /sys/kernel/debug 2>/dev/null || /bin/mount -t debugfs debugfs /sys/kernel/debug 2>/dev/null

# Автозагрузка модулей по modalias: udev/eudev в этом образе нет, узлы создаёт
# devtmpfs, а модули (WiFi-драйверы, exFAT/NTFS, ...) должен грузить помощник
# uevent. Путь к нему зашит и в ядро (CONFIG_UEVENT_HELPER_PATH), здесь -
# страховка на случай, если кто-то его сбросит.
[ -x /sbin/hotplug ] && echo /sbin/hotplug > /proc/sys/kernel/hotplug 2>/dev/null

# loopback ОБЯЗАТЕЛЬНО должен быть поднят: доставка пакетов на собственный
# адрес (в том числе 192.168.77.1 на usb0 при входе по SSH с ПК) идёт через lo.
# Без этого "ip route get 127.0.0.1" отвечает "Network unreachable", а любое
# локальное соединение (dropbear, udhcpd, nc) не работает.
/bin/ip link set lo up 2>/dev/null || /sbin/ifconfig lo up 2>/dev/null

# boot partition (vfat) - lets you edit /boot/extlinux/extlinux.conf from the board
if [ -b /dev/mmcblk0p1 ]; then
    mkdir -p /boot
    mountpoint -q /boot || /bin/mount -t vfat -o rw /dev/mmcblk0p1 /boot 2>/dev/null
fi

[ -x /etc/init.d/local ] && /etc/init.d/local
exit 0
EOF
chmod 755 "$DEST/etc/init.d/rcS"

cat > "$DEST/etc/init.d/local" <<'EOF'
#!/bin/sh
# Runs at the end of sysinit (после монтирования /proc, /sys и /boot).

# --- одноразовая загрузка (команда bootnext) --------------------------------
# bootnext ставит default=<пункт> и создаёт /boot/bootonce из ДВУХ строк:
# пункт и прежний default. Мы сюда попали - значит плата загрузилась успешно,
# поэтому возвращаем прежний default и снимаем метку: следующая загрузка (в том
# числе после зависания и выключения питания) снова будет рабочей.
if [ -e /boot/bootonce ]; then
    ONE=$(sed -n 1p /boot/bootonce 2>/dev/null)
    PREV=$(sed -n 2p /boot/bootonce 2>/dev/null | tr -cd 'A-Za-z0-9_-')
    if [ -z "$PREV" ]; then
        # метка из одной строки (b013/b014) - возвращаем заводской пункт
        PREV=$(cat /etc/boot-default 2>/dev/null | tr -cd 'A-Za-z0-9_-')
        [ -n "$PREV" ] || PREV=lowopp
    fi
    rm -f /boot/bootonce
    if [ -w /boot/extlinux/extlinux.conf ]; then
        sed -i "s|^[[:space:]]*default[[:space:]].*|default $PREV|" /boot/extlinux/extlinux.conf
        sync
        echo "[bootnext] разовая загрузка '$ONE' выполнена, default снова $PREV"
    fi
fi

# --- аппаратный watchdog (опционально, включается командой `wdt on`) ----------
# Драйвер sunxi_wdt делает probe (узел включён во всех DTB с b015), но таймер
# при probe НЕ стартует. Если пользователь включил фидер командой `wdt on`,
# флаг лежит в /etc/wdt-enabled - поднимаем фидер и здесь, чтобы защита от
# зависания переживала перезагрузку.
if [ -f /etc/wdt-enabled ] && [ -e /dev/watchdog ]; then
    WDT_T=16
    WDT_PING=8
    . /etc/wdt-enabled 2>/dev/null
    # -F: фидер в foreground, в фон уводим мы и пишем PID в /run/wdt.pid -
    # тот же договор, что у команды `wdt on` (см. /usr/local/bin/wdt)
    watchdog -F -T "$WDT_T" -t "$WDT_PING" /dev/watchdog >/dev/null 2>&1 &
    echo "$!" > /run/wdt.pid
    sleep 1
    WDT_PID=$(cat /run/wdt.pid 2>/dev/null)
    WDT_ST=$(sed 's/.*) //' "/proc/$WDT_PID/stat" 2>/dev/null | cut -d' ' -f1)
    if [ -n "$WDT_PID" ] && kill -0 "$WDT_PID" 2>/dev/null && [ "$WDT_ST" != Z ]; then
        echo "[wdt] фидер запущен: таймаут ${WDT_T} с, пинг каждые ${WDT_PING} с (pid $WDT_PID)"
    else
        echo "[wdt] не удалось запустить фидер"
        rm -f /run/wdt.pid
    fi
fi

# --- USB-gadget (сеть + SSH) через порт micro-USB, b017+ --------------------
# Поднимается автоматически, если есть /etc/usbnet-enabled (его ставит команда
# `usbnet auto on`) ИЛИ в append пункта загрузки есть usbnet=1.
# Отключить без перепрошивки: добавить в append строку usbnet=0 или nousb=1
# (файл /boot/extlinux/extlinux.conf правится прямо с платы, /boot смонтирован).
CMDLINE=$(cat /proc/cmdline 2>/dev/null)
want_usb=0; want_ssh=0
[ -f /etc/usbnet-enabled ] && want_usb=1
[ -f /etc/ssh-enabled ] && want_ssh=1
case "$CMDLINE" in *usbnet=1*) want_usb=1 ;; esac
case "$CMDLINE" in *ssh=1*)    want_ssh=1 ;; esac
case "$CMDLINE" in *usbnet=0*|*nousb=1*) want_usb=0 ;; esac
case "$CMDLINE" in *ssh=0*)    want_ssh=0 ;; esac

if [ -x /usr/local/bin/usbnet ] && { [ "$want_usb" = 1 ] || [ "$want_ssh" = 1 ]; }; then
    # в фоне и с задержкой: генерация ключей хоста dropbear занимает пару
    # секунд, а UDC появляется не мгновенно после probe musb
    if [ "$want_usb" = 1 ]; then
        ( sleep 4; /usr/local/bin/usbnet on ) &
    else
        ( sleep 3; /usr/local/bin/usbnet ssh on ) &
    fi
fi

# --- USB-Ethernet адаптер (для разъёма на месте WiFi-модуля) -----------------
# Если в cmdline есть eth=1 - пытаемся получить адрес по DHCP на любом
# USB-сетевом адаптере (и поднимаем SSH, чтобы на него можно было зайти).
case "$CMDLINE" in
    *eth=1*) [ -x /usr/local/bin/usbnet ] && ( sleep 6; /usr/local/bin/usbnet eth ) & ;;
esac

# --- WiFi (b021+): автоподключение к сохранённой сети ------------------------
# Флаг /etc/wifi-enabled ставит команда `wifi auto on`. Подключение идёт в фоне
# и с задержкой: модуль драйвера грузится по uevent не мгновенно, а
# wpa_supplicant не должен мешать подъёму USB-гаджета (он стартует раньше).
if [ -f /etc/wifi-enabled ] && [ -x /usr/local/bin/wifi ]; then
    ( sleep 8; /usr/local/bin/wifi up >>/var/log/wifi.log 2>&1 ) &
fi
# --- haveged: энтропия (без батарейки RTC и на голой плате crng init идёт ~70 с,
# --- а до этого dropbear/wpa_supplicant могут тормозить) ---------------------
if [ -x /usr/sbin/haveged ]; then
    /usr/sbin/haveged -w 1024 >/dev/null 2>&1 || true
fi
exit 0
EOF
chmod 755 "$DEST/etc/init.d/local"

# autologin helper (used by the commented inittab line above)
cat > "$DEST/sbin/autologin" <<'EOF'
#!/bin/sh
exec /bin/login -f root
EOF
chmod 755 "$DEST/sbin/autologin"

cat > "$DEST/usr/local/bin/autologin-on" <<'EOF'
#!/bin/sh
# Вход без запроса логина (правим inittab, затем reboot)
cp /etc/inittab /etc/inittab.bak 2>/dev/null
sed -i 's|^ttyS0::respawn:/sbin/getty -L 115200 ttyS0 vt100|#ttyS0::respawn:/sbin/getty -L 115200 ttyS0 vt100|' /etc/inittab
sed -i 's|^#ttyS0::respawn:/sbin/getty -n -L -l /sbin/autologin|ttyS0::respawn:/sbin/getty -n -L -l /sbin/autologin|' /etc/inittab
grep -n '^ttyS0' /etc/inittab
